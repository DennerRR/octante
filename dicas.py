def chaves_da_pagina(endpoint):
    """Ordem de precedência (do mais geral ao mais específico) para um endpoint."""
    if not endpoint:
        return ["*"]
    chaves = ["*"]
    if "." in endpoint:
        chaves.append(endpoint.split(".")[0])
    elif endpoint.startswith("parte"):
        chaves.append("partes")
    elif endpoint in ("projeto_novo", "projeto_editar"):
        chaves.append("projeto")
    else:
        chaves.append(endpoint)
    chaves.append(endpoint)
    return chaves


def dicas_da_pagina(endpoint):
    out = {}
    for chave in chaves_da_pagina(endpoint):
        for campo, (exemplo, ajuda) in DICAS.get(chave, {}).items():
            out[campo] = [exemplo, ajuda]
    return out
